// Rewrites src/seo/pages/index.ts from the page files in src/seo/pages/<kind>/*.ts (run after adding
// a page: node tools/seo-index.mjs). Explicit imports, because vite.config.ts loads this list
// through esbuild, where import.meta.glob doesn't exist.
import { readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const dir = resolve(import.meta.dirname, "../src/seo/pages");
const kinds = ["industry", "compare", "versus", "feature", "guide"];
const files = kinds.flatMap((k) => {
  try {
    return readdirSync(resolve(dir, k)).filter((f) => f.endsWith(".ts")).sort().map((f) => `${k}/${f.slice(0, -3)}`);
  } catch {
    return [];
  }
});
const id = (f, i) => `p${i}`;
writeFileSync(
  resolve(dir, "index.ts"),
  `// Every page in the SEO library. Generated by tools/seo-index.mjs from the files in this folder.
import type { SeoPage } from "../types";
${files.map((f, i) => `import { page as ${id(f, i)} } from "./${f}";`).join("\n")}

export const PAGES: SeoPage[] = [${files.map(id).join(", ")}];
`,
);
console.log(`src/seo/pages/index.ts: ${files.length} pages`);
