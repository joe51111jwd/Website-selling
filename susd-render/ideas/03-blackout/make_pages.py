#!/usr/bin/env python3
"""Print and paint the Blackout pages: the stand-in for "print 5 or 6 real pages of the manuscript,
then someone paints them out with brush and ink" (docs/09, idea 3).

  python3 ideas/03-blackout/make_pages.py            (writes ideas/03-blackout/tex/)

Two A4 sheets, laid out in millimetres and drawn at 16 px/mm:
  book  a page of the book, set large in Ortica Angular Bold (the project's face for Michael's
        voice), every line painted out except "Every hire compounds complexity before it compounds
        capacity." [M 696]. The ink is dry.
  boot  a page of the SUSD Bootloader printout, set in Ortica Linear Bold, painted out down to
        its first question, "How many people are on your team?" [BL 4197]. The last strokes are
        still wet.

The body text on each sheet is Michael's own (Bootloader lines, cited below), so the few words a
dry brush lets through are his too. The type is large (about 32 pt on A4) on purpose: the 09 entry
says a whole page can't be read on a phone, so the pages are printed big enough for a close crop.

Outputs per sheet, all the same size (3360 x 4752 px):
  <name>_toner.png   printed text coverage (white = toner)
  <name>_ink.png     R ink coverage, G ink thickness (relief and gloss), B wet ink
  <name>_cockle.npy  paper height in mm at 2 px/mm (the sheet buckles where it took wet ink)
  <name>_layout.json line boxes in mm (for framing the cameras and placing the HTML)

The ink model, per stroke: a flat brush dragged left to right along a line of text. The stroke's
edges are ragged at two scales, it starts with a pressed, rounded touch-down and a small pool, and
it runs dry towards its end, outer bristles first, so it breaks into long streaks parallel to the
stroke (dry brush). Strokes overlap; around the kept sentence a narrower brush cuts in, leaving a
wobbly white margin. Nothing here is generated by AI: it is arithmetic on noise.
"""
import json, math, os
import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
TYPE = os.path.join(ROOT, 'docs', 'type', 'system')
OUT = os.path.join(HERE, 'tex')
os.makedirs(OUT, exist_ok=True)

P = 16.0                       # px per mm
PW, PH = 210.0, 297.0          # A4
W, H = int(PW * P), int(PH * P)
EM = 11.2                      # mm (about 32 pt)
PITCH = 1.22 * EM
ASC, DESC = 0.775 * EM, 0.26 * EM
LEFT, MEASURE = 30.0, 150.0
TOP = 30.0                     # top of the first line's ascenders
INDENT = 1.2 * EM


def font(name, mm):
    return ImageFont.truetype(os.path.join(TYPE, name), int(round(mm * P)), layout_engine=ImageFont.Layout.RAQM)


# ----------------------------------------------------------------------------- noise helpers

def vnoise(h, w, cell_y, cell_x, rng):
    """Smooth value noise, cells cell_y x cell_x px, returns float32 (h, w) in about [-1, 1]."""
    gy, gx = max(2, int(math.ceil(h / cell_y)) + 2), max(2, int(math.ceil(w / cell_x)) + 2)
    g = rng.standard_normal((gy, gx)).astype(np.float32)
    im = Image.fromarray(g, 'F').resize((int(gx * cell_x), int(gy * cell_y)), Image.BICUBIC)
    a = np.asarray(im, dtype=np.float32)
    oy, ox = rng.integers(0, max(1, int(cell_y))), rng.integers(0, max(1, int(cell_x)))
    a = a[oy:oy + h, ox:ox + w]
    return a / (a.std() + 1e-6) * 0.5


def noise1d(n, cell, rng):
    return vnoise(1, n, 1, cell, rng)[0]


def box_blur(a, r):
    """Separable box blur, radius r px, three passes ~ gaussian (sigma ~ r)."""
    r = int(max(1, r))
    for _ in range(3):
        for ax in (0, 1):
            c = np.cumsum(np.pad(a, [(r + 1, r) if i == ax else (0, 0) for i in range(2)], mode='edge'), axis=ax, dtype=np.float64)
            sl_hi = [slice(None)] * 2; sl_lo = [slice(None)] * 2
            sl_hi[ax] = slice(2 * r + 1, None); sl_lo[ax] = slice(0, -(2 * r + 1))
            a = ((c[tuple(sl_hi)] - c[tuple(sl_lo)]) / (2 * r + 1)).astype(np.float32)
    return a


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3 - 2 * t)


# ----------------------------------------------------------------------------- typesetting

def smart(t):
    import re
    t = re.sub(r"(^|[\s(])'", '\\1\u2018', t); t = t.replace("'", '\u2019')
    t = re.sub(r'(^|[\s(])"', '\\1\u201c', t); t = t.replace('"', '\u201d')
    return t


def wrap(text, ft, first_indent, measure):
    text = smart(text)
    words, lines, cur, ind = text.split(' '), [], '', first_indent
    for w_ in words:
        t = (cur + ' ' + w_) if cur else w_
        if ft.getlength(t) / P + ind <= measure or not cur:
            cur = t
        else:
            lines.append((ind, cur)); cur, ind = w_, 0.0
    if cur:
        lines.append((ind, cur))
    return lines


def set_page(paras, face, quote_indent=0.0):
    """paras: list of (text, kind) where kind in body|cont|keep|quote|keepquote|head.
    Returns line dicts with mm boxes."""
    ft = font(face, EM)
    lines = []
    for text, kind in paras:
        q = kind in ('quote', 'keepquote')
        ind = 0.0 if kind in ('cont', 'head') or q else INDENT
        meas = MEASURE - (quote_indent if q else 0.0)
        for li, (ii, t) in enumerate(wrap(text, ft, ind, meas)):
            x0 = LEFT + ii + (quote_indent if q else 0.0)
            lines.append(dict(text=t, x0=x0, x1=x0 + ft.getlength(t) / P, keep=kind.startswith('keep'), kind=kind))
    for i, L in enumerate(lines):
        L['base'] = TOP + ASC + i * PITCH
        L['top'], L['bot'] = L['base'] - ASC, L['base'] + DESC
    return lines, ft


def draw_toner(lines, ft, extra):
    im = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(im)
    for L in lines:
        d.text((L['x0'] * P, L['base'] * P), L['text'], font=ft, fill=255, anchor='ls')
    for (x, y, t, f, anchor) in extra:
        d.text((x * P, y * P), t, font=f, fill=255, anchor=anchor)
    a = np.asarray(im, dtype=np.float32) / 255.0
    return a


# ----------------------------------------------------------------------------- the brush

def stroke(acc, x0, x1, yc, width, rng, load=1.0, slope=0.0, wet=False, round_start=1.0, tail=1.0):
    """Paint one flat-brush stroke from x0 to x1 (mm) centred on yc, into acc (dict of arrays)."""
    pad = width * 0.9 + 3
    bx0, bx1 = max(0, int((x0 - 6) * P)), min(W, int((x1 + 14) * P))
    by0, by1 = max(0, int((yc - pad) * P)), min(H, int((yc + pad) * P))
    if bx1 <= bx0 or by1 <= by0:
        return
    nx, ny = bx1 - bx0, by1 - by0
    xs = (np.arange(nx, dtype=np.float32) + bx0 + 0.5) / P
    ys = (np.arange(ny, dtype=np.float32) + by0 + 0.5) / P
    L = max(x1 - x0, 1.0)
    # the hand: a slow wobble and a slight slope
    wob = noise1d(nx, 40 * P, rng) * 0.55 + noise1d(nx, 9 * P, rng) * 0.18
    cen = yc + slope * (xs - x0) + wob
    hw = width / 2 * (1 + 0.035 * noise1d(nx, 14 * P, rng))
    # lift-off: the last few mm narrow a little
    hw = hw * (1 - 0.18 * smoothstep(x1 - 7, x1 + 2, xs) * tail)
    # ragged edges, two scales, independent top and bottom
    e_top = noise1d(nx, 2.2 * P, rng) * 0.22 + noise1d(nx, 0.45 * P, rng) * 0.07
    e_bot = noise1d(nx, 2.2 * P, rng) * 0.22 + noise1d(nx, 0.45 * P, rng) * 0.07
    Y = ys[:, None]
    top = (cen - hw + e_top)[None, :]
    bot = (cen + hw + e_bot)[None, :]
    inside = smoothstep(-0.05, 0.05, np.minimum(Y - top, bot - Y))
    v = np.clip((Y - cen[None, :]) / hw[None, :], -1.3, 1.3)
    X = xs[None, :]
    # touch-down: rounded/tilted start; the end edge spreads into bristle tails
    tilt = rng.uniform(-1.2, 1.2)
    xstart = x0 + round_start * 1.6 * v * v + tilt * v
    inside *= smoothstep(-0.06, 0.06, X - xstart)
    tails = vnoise(ny, 1, 0.35 * P, 1, rng)[:, :1] * 1.8 * tail     # per bristle, mm
    xend = x1 - 1.4 * v * v + tails
    inside *= smoothstep(-0.06, 0.06, xend - X)
    # dryness along the stroke: outer bristles first, more towards the end
    prog = np.clip((X - x0) / L, 0, 1)
    dry = (prog ** 4) * (1.0 / max(load, 0.2)) * 0.9 + 0.35 * np.abs(v) ** 6 - 0.75
    dry += 0.75 * smoothstep(x1 - 2.5, x1 + 4.5, X) * tail
    # bristle streaks: long along the stroke, fine across it
    streak = vnoise(ny, nx, 0.22 * P, 16 * P, rng) * 0.6 + vnoise(ny, nx, 0.6 * P, 40 * P, rng) * 0.4 + 0.5
    cov = inside * smoothstep(dry - 0.06, dry + 0.06, streak)
    # thickness: heavy where loaded, a pool at the touch-down, thin where dry
    pool = np.exp(-(((X - (x0 + 2.5)) / 3.0) ** 2) - ((Y - cen[None, :]) / (hw[None, :] * 0.8)) ** 2)
    thick = cov * (0.55 + 0.45 * np.clip(1 - dry, 0, 1)) + 0.25 * pool * inside
    thick *= 1 + 0.18 * vnoise(ny, nx, 0.5 * P, 6 * P, rng)
    if wet:
        thick = thick * 1.6 + 0.25 * inside
    sl = (slice(by0, by1), slice(bx0, bx1))
    acc['cov'][sl] = 1 - (1 - acc['cov'][sl]) * (1 - np.clip(cov, 0, 1))
    acc['thick'][sl] += np.clip(thick, 0, None)
    if wet:
        acc['wet'][sl] = np.maximum(acc['wet'][sl], inside * smoothstep(0.02, 0.2, cov + 0.1 * pool))


def paint_page(lines, rng, wet_lines=(), extra_boxes=()):
    acc = dict(cov=np.zeros((H, W), np.float32), thick=np.zeros((H, W), np.float32), wet=np.zeros((H, W), np.float32))
    inked = [L for L in lines if not L['keep']]
    for i, L in enumerate(lines):
        if L['keep']:
            continue
        x0 = L['x0'] - rng.uniform(2.5, 4.5)
        x1 = L['x1'] + rng.uniform(2.0, 7.0)
        yc = (L['top'] + L['bot']) / 2 + rng.uniform(-0.6, 0.6)
        width = EM * rng.uniform(1.66, 1.84)
        wet = i in wet_lines
        # long lines take two strokes: the brush is reloaded part way
        if x1 - x0 > 95 and rng.random() < 0.8:
            split = x0 + (x1 - x0) * rng.uniform(0.28, 0.72)
            stroke(acc, x0, split + rng.uniform(4, 12), yc, width, rng, load=rng.uniform(0.9, 1.4),
                   slope=rng.uniform(-0.012, 0.012), wet=wet, tail=0.6)
            stroke(acc, split - rng.uniform(3, 9), x1, yc + rng.uniform(-0.8, 0.8), width, rng,
                   load=rng.uniform(0.75, 1.2), slope=rng.uniform(-0.012, 0.012), wet=wet)
        else:
            ld = rng.uniform(0.55, 0.8) if rng.random() < 0.2 else rng.uniform(0.9, 1.4)
            stroke(acc, x0, x1, yc, width, rng, load=ld, slope=rng.uniform(-0.012, 0.012), wet=wet,
                   tail=float(rng.choice([1.0, 0.6, 0.2])))
        # a second pass over about a third of the lines (the painter goes back over thin spots)
        if rng.random() < 0.18:
            a = rng.uniform(x0, x0 + (x1 - x0) * 0.5)
            stroke(acc, a, min(x1, a + rng.uniform(25, 70)), yc + rng.uniform(-2.5, 2.5), width * rng.uniform(0.8, 1.0),
                   rng, load=1.3, slope=rng.uniform(-0.02, 0.02), wet=wet, round_start=0.6)
    for (bx0, bx1, byc, bw, wet) in extra_boxes:     # small strokes (running head)
        stroke(acc, bx0, bx1, byc, bw, rng, load=1.4, wet=wet)
    # a few drops shaken off the brush: one main drop, a couple of satellites, in the right margin
    yy, xx = np.mgrid[0:H, 0:W]
    for _ in range(3):
        L = inked[rng.integers(0, len(inked))]
        cx, cy = L['x1'] + rng.uniform(8, 22), L['base'] + rng.uniform(-6, 6)
        for k in range(rng.integers(1, 4)):
            r = rng.uniform(0.35, 0.9) if k == 0 else rng.uniform(0.12, 0.3)
            ox, oy = (0, 0) if k == 0 else (rng.uniform(-4, 4), rng.uniform(-3, 3))
            x_, y_ = int((cx + ox) * P), int((cy + oy) * P)
            R = int(r * P) + 3
            sl = (slice(max(0, y_ - R), y_ + R), slice(max(0, x_ - R), x_ + R))
            d = np.hypot(xx[sl] - x_, (yy[sl] - y_) * rng.uniform(0.85, 1.15)) / P
            blob = smoothstep(r + 0.04, r - 0.04, d)
            acc['cov'][sl] = np.maximum(acc['cov'][sl], blob)
            acc['thick'][sl] += blob * 1.4
    return acc


def protect(acc, lines, rng, m_side=2.8, m_vert=1.8):
    """Cut in around the kept lines with a small brush: a white island with a wobbly edge."""
    keep = np.zeros((H, W), np.float32)
    for L in lines:
        if not L['keep']:
            continue
        y0, y1 = int((L['top'] - m_vert) * P), int((L['bot'] + m_vert) * P)
        x0, x1 = int((L['x0'] - m_side) * P), int((L['x1'] + m_side) * P)
        keep[y0:y1, x0:x1] = 1.0
    keep = box_blur(keep, 1.1 * P)                      # round the steps the way a hand would
    edge = vnoise(H, W, 4 * P, 4 * P, rng) * 0.12 + vnoise(H, W, 0.8 * P, 0.8 * P, rng) * 0.05
    k = smoothstep(0.47, 0.53, keep + edge)
    for key in ('cov', 'thick', 'wet'):
        acc[key] *= (1 - k)
    # the cut-in edge holds a little more ink (the small brush is pressed along it)
    ring = smoothstep(0.25, 0.47, keep + edge) * (1 - k)
    acc['thick'] += 0.35 * ring * (acc['cov'] > 0.5)
    return k


def close_gaps(acc, keep, k_mm=0.5):
    """Review fix: fill the thin white slits left INSIDE the ink where the dry outer bristles of two
    overlapping strokes happen to line up (they rendered as rows of white dashes, which a hand going
    back over the page would not leave). A slit is a no-ink run at most k_mm tall with ink above and
    below, and along its row it must end in ink at both ends. The dry tails at stroke ends open onto
    bare paper, so they are left alone; so is the cut-in island around the kept line."""
    ink = acc['cov'] > 0.5
    K = int(round(k_mm * P))
    big = 10 ** 6
    up = np.full(ink.shape, big, np.int32); dn = np.full(ink.shape, big, np.int32)
    for d in range(K, 0, -1):          # nearest ink above / below within K px
        up[d:][ink[:-d]] = d
        dn[:-d][ink[d:]] = d
    cand = ~ink & (up + dn - 1 <= K) & (keep < 0.01)
    cols = np.arange(ink.shape[1], dtype=np.int32)[None, :]
    stop = ~cand                                            # the first non-slit pixel either side
    left = np.maximum.accumulate(np.where(stop, cols, -1), axis=1)
    right = np.flip(np.minimum.accumulate(np.flip(np.where(stop, cols, big), 1), axis=1), 1)
    rows = np.arange(ink.shape[0])[:, None]
    l_ink = (left >= 0) & ink[rows, np.clip(left, 0, ink.shape[1] - 1)]
    r_ink = (right < big) & ink[rows, np.clip(right, 0, ink.shape[1] - 1)]
    fill = (cand & l_ink & r_ink).astype(np.float32)
    fill = np.maximum(fill, np.maximum(np.roll(fill, 1, 0), np.roll(fill, -1, 0)))   # cover the soft edges
    fill *= (keep < 0.01)
    inkf = ink.astype(np.float32)
    norm = box_blur(inkf, 4) + 1e-4
    for key in ('thick', 'wet'):
        local = box_blur(acc[key] * inkf, 4) / norm
        acc[key] = acc[key] * (1 - fill) + np.maximum(acc[key], local) * fill
    acc['cov'] = np.maximum(acc['cov'], fill)
    return float(fill.mean())


def cockle(acc, rng, wet_gain=1.0):
    """Paper height (mm) at 2 px/mm: swells where it took ink, buckles in broad horizontal ridges,
    and the corners lift a little off the table."""
    s = int(P // 2)
    cov = acc['cov'][::s, ::s].copy() + 0.6 * acc['wet'][::s, ::s] * wet_gain
    h, w = cov.shape
    local = box_blur(cov, 2) * 0.10                      # 1 mm: each stroke stands a little proud
    broad = np.clip(box_blur(cov, 36) * 1.6, 0, 1)       # the swelling spreads well into the margins
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32) / 2.0
    # waves running along the strokes, ~24 mm apart, bent and broken up by noise
    warp = vnoise(h, w, 50, 70, rng) * 9.0 + vnoise(h, w, 16, 30, rng) * 2.5
    lam = 24.0 * (1 + 0.15 * vnoise(h, w, 120, 120, rng))
    wave = 0.5 + 0.5 * np.sin(2 * np.pi * (yy + warp) / lam + 0.04 * xx)
    amp = 0.75 * (0.7 + 0.3 * vnoise(h, w, 40, 40, rng))
    buck = broad * wave * amp
    dx = np.minimum(xx, PW - xx); dy = np.minimum(yy, PH - yy)
    d = np.minimum(dx, dy)
    curl = (1 - smoothstep(0, 18, d)) * (0.6 + 0.4 * vnoise(h, w, 60, 60, rng)) * 0.9
    corner = np.exp(-((dx / 30) ** 2 + (dy / 30) ** 2)) * 1.2
    h = local + buck + curl + corner
    # paper lying on a flat sheet can only buckle upwards: about a quarter of it touches down
    h = np.clip(h - np.percentile(h, 3), 0, None)
    return h.astype(np.float32)


def save(name, toner, acc, ck, lines, extra=None):
    Image.fromarray((np.clip(toner, 0, 1) * 255).astype(np.uint8), 'L').save(os.path.join(OUT, name + '_toner.png'))
    thick = np.clip(acc['thick'] / 2.2, 0, 1)
    rgb = np.stack([np.clip(acc['cov'], 0, 1), thick, np.clip(acc['wet'], 0, 1)], -1)
    Image.fromarray((rgb * 255).astype(np.uint8), 'RGB').save(os.path.join(OUT, name + '_ink.png'))
    np.save(os.path.join(OUT, name + '_cockle.npy'), ck)
    lay = dict(page_mm=[PW, PH], px_per_mm=P, em_mm=EM, lines=lines)
    if extra:
        lay.update(extra)
    json.dump(lay, open(os.path.join(OUT, name + '_layout.json'), 'w'), indent=1)
    # a quick flat preview (what a scanner would see)
    paper = np.full((H, W, 3), (0.93, 0.935, 0.94), np.float32)
    tn = toner[..., None] * np.array([0.06, 0.06, 0.065])
    col = paper * (1 - toner[..., None]) + tn
    ink = np.array([0.035, 0.035, 0.04])
    c = np.clip(acc['cov'], 0, 1)[..., None]
    col = col * (1 - c) + ink * c
    Image.fromarray((np.clip(col, 0, 1) ** (1 / 1.0) * 255).astype(np.uint8)).resize((W // 4, H // 4), Image.LANCZOS) \
        .save(os.path.join(OUT, name + '_preview.png'))


# ----------------------------------------------------------------------------- the two sheets

def book():
    rng = np.random.default_rng(31)
    paras = [
        # BL 802, continuing from the page before
        ("more people, more growth. That's the only axis anyone talks about.", 'cont'),
        ("Every hire compounds complexity before it compounds capacity.", 'keep'),          # M 696
        ("One-dimensional scaling looks like progress but it's just a line getting longer. "
         "You're not building volume. You're not building mass. You're just extending in one "
         "direction until you snap.", 'body'),                                                # BL 812
        ("Three-dimensional scaling builds a structure. Each cycle adds depth, width, and height. "
         "The business has volume. It has weight. It can hold load.", 'body'),              # BL 814
        ("You can't build a building with only height. You need all three dimensions or it "
         "topples.", 'body'),                                                                # BL 816
    ]
    lines, ft = set_page(paras, 'Ortica-AngularBold.otf')
    lines = [L for L in lines if L['bot'] < PH - 22]
    small = font('Ortica-AngularBold.otf', 3.3)
    extra = [(LEFT, 17.0, 'Scaling Up-Side-Down', small, 'ls'), (PW - 30.0, 17.0, '38', small, 'rs')]
    toner = draw_toner(lines, ft, extra)
    rh_w = small.getlength('Scaling Up-Side-Down') / P
    acc = paint_page(lines, rng, extra_boxes=[(LEFT - 1.5, LEFT + rh_w + 3, 17.0 - 1.2, 6.5, False)])
    keep = protect(acc, lines, rng)
    print('  book: slits closed on %.3f%% of the sheet' % (100 * close_gaps(acc, keep)))
    ck = cockle(acc, rng)
    save('book', toner, acc, ck, lines, dict(folio=[PW - 30.0, 17.0]))
    return lines


def boot():
    rng = np.random.default_rng(57)
    paras = [
        # BL 4185 (end of the paragraph before), BL 4189, BL 4195, BL 4197, BL 4199, BL 4201
        ('The answer is: "You\'re describing when to move, not where the math stabilizes."', 'cont'),
        ('4.2 Entry Point Routing', 'head'),
        ('Step 0: The Locating Question (Ask First)', 'head'),
        ('“How many people are on your team?”', 'keepquote'),
        ('Clarification: "Team" means coordination load, not payroll headcount. Count everyone they '
         'carry in their head — employee or contractor, anyone they align weekly, manage output '
         'for, or coordinate with other team members.', 'cont'),
        ("This single question reveals location on the destination map, physics that apply, and what "
         "advice will fit vs. make things worse.", 'body'),
    ]
    lines, ft = set_page(paras, 'Ortica-LinearBold.otf', quote_indent=1.2 * EM)
    lines = [L for L in lines if L['bot'] < PH - 22]
    small = font('Ortica-LinearBold.otf', 3.3)
    extra = [(LEFT, 17.0, 'SUSD Bootloader', small, 'ls'), (PW - 30.0, 17.0, '214', small, 'rs')]
    toner = draw_toner(lines, ft, extra)
    ki = [i for i, L in enumerate(lines) if L['keep']]
    wet = {ki[-1] + 1, ki[-1] + 2}          # the last strokes, just under the question, still wet
    acc = paint_page(lines, rng, wet_lines=wet)
    keep = protect(acc, lines, rng)
    print('  boot: slits closed on %.3f%% of the sheet' % (100 * close_gaps(acc, keep)))
    ck = cockle(acc, rng, wet_gain=1.6)
    save('boot', toner, acc, ck, lines, dict(folio=[PW - 30.0, 17.0], wet_lines=sorted(wet)))
    return lines


if __name__ == '__main__':
    for fn in (book, boot):
        ls = fn()
        print(fn.__name__, len(ls), 'lines')
        for L in ls:
            print('  %s %6.1f..%6.1f  base %6.1f  %s' % ('KEEP' if L['keep'] else '    ', L['x0'], L['x1'], L['base'], L['text']))
