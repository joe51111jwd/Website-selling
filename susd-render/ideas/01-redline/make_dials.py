#!/usr/bin/env python3
"""Paint the printed parts of the Redline panel: two dial faces and two engraved label plates.

  python3 ideas/01-redline/make_dials.py        (writes ideas/01-redline/tex/*.png)

This is the stand-in for "print our own dial faces" in the 09 entry: the faces are what we would
send to a printer and fit into a used gauge. Drawn at 2x and filtered down (anti-aliased), in B612
(the Airbus cockpit face already in our type system), then aged a little: uneven black, a faint
yellowing of the white ink, a few dust specks. Nothing here is generated by AI.

Left dial, COORDINATION: a linear pathways scale 0..120. A long tick at every hire (the triangular
numbers n(n-1)/2: 0, 1, 3, 6, 10 ... 66, 78 ... 120), so the gaps between hires widen as you read
round; an inner ring numbers the people at each of those ticks. Red band from 72 (between 12 and
13 people) to the end.
Right dial, CAPACITY: people 0..22, linear, so one person is always the same step. The two scales are
calibrated so the needles point the same way at twelve (66 pathways ~ 12 people): before twelve
capacity leads, after it complexity does. That calibration is ours (see NOTES.md).
"""
import math, os
import numpy as np
from PIL import Image, ImageDraw, ImageFont, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
TYPE = os.path.join(ROOT, 'docs', 'type', 'system')
OUT = os.path.join(HERE, 'tex')
os.makedirs(OUT, exist_ok=True)

S = 4096                      # drawn at 2x, saved at 2048
FACE_MM = 151.0               # the printed disc
PX = S / FACE_MM              # px per mm
C = S / 2
INK = (226, 223, 212)         # white ink, a little aged
GREY = (150, 148, 140)
RED = (176, 34, 28)           # signal red, matte
BLACK = (17, 17, 17)

bold = lambda mm: ImageFont.truetype(os.path.join(TYPE, 'B612-Bold.ttf'), int(mm * PX))
reg = lambda mm: ImageFont.truetype(os.path.join(TYPE, 'B612-Regular.ttf'), int(mm * PX))


def pt(r_mm, deg):
    """deg clockwise from 12 o'clock."""
    a = math.radians(deg)
    return C + r_mm * PX * math.sin(a), C - r_mm * PX * math.cos(a)


def tick(d, deg, r0, r1, w_mm, col):
    x0, y0 = pt(r0, deg); x1, y1 = pt(r1, deg)
    d.line([(x0, y0), (x1, y1)], fill=col, width=max(1, int(w_mm * PX)))


def text_c(d, xy, s, font, col):
    d.text(xy, s, font=font, fill=col, anchor='mm')


def band(img, deg0, deg1, r0, r1, col):
    m = Image.new('L', img.size, 0)
    md = ImageDraw.Draw(m)
    box = lambda r: [C - r * PX, C - r * PX, C + r * PX, C + r * PX]
    md.pieslice(box(r1), deg0 - 90, deg1 - 90, fill=255)
    md.pieslice(box(r0), deg0 - 90, deg1 - 90, fill=0)
    img.paste(Image.new('RGB', img.size, col), (0, 0), m)


def age(img, seed):
    """Uneven black, faint yellowing of the ink, dust specks. Subtle: a real dial, not a prop."""
    rng = np.random.default_rng(seed)
    a = np.asarray(img).astype(np.float32) / 255.0
    h, w = a.shape[:2]
    # low-frequency unevenness (+-4 %)
    lo = rng.normal(0, 1, (12, 12)).astype(np.float32)
    lo = np.asarray(Image.fromarray(((lo - lo.min()) / (np.ptp(lo) + 1e-6) * 255).astype(np.uint8)).resize((w, h), Image.BICUBIC)) / 255.0
    a *= (0.96 + 0.08 * lo)[..., None]
    # ink yellows a touch more towards the lower half (sun from above through the glass for decades)
    yy = np.linspace(0, 1, h, dtype=np.float32)[:, None]
    lum = a.mean(axis=2)
    ink = np.clip((lum - 0.3) / 0.5, 0, 1)
    a[..., 2] -= ink * (0.02 + 0.03 * yy)
    # dust specks on the dial (pale, tiny)
    n = 260
    ys, xs = rng.integers(0, h, n), rng.integers(0, w, n)
    for y, x, s in zip(ys, xs, rng.uniform(1.0, 3.0, n)):
        r = int(s)
        a[max(0, y - r):y + r, max(0, x - r):x + r] = np.maximum(a[max(0, y - r):y + r, max(0, x - r):x + r], 0.30)
    a = np.clip(a, 0, 1)
    out = Image.fromarray((a * 255).astype(np.uint8))
    return out


def base():
    img = Image.new('RGB', (S, S), BLACK)
    return img, ImageDraw.Draw(img)


def ang(v, vmax):
    return -135.0 + 270.0 * v / vmax


def coordination():
    img, d = base()
    VMAX = 120.0
    tri = [n * (n - 1) // 2 for n in range(1, 17)]          # 0 .. 120 (16 people)
    band(img, ang(72, VMAX), ang(VMAX, VMAX), 60.0, 67.0, RED)
    d = ImageDraw.Draw(img)
    # outer rule
    d.arc([C - 67.2 * PX, C - 67.2 * PX, C + 67.2 * PX, C + 67.2 * PX], ang(0, VMAX) - 90, ang(VMAX, VMAX) - 90,
          fill=INK, width=int(0.35 * PX))
    for v in range(0, 121, 2):                               # minor ticks every 2 pathways
        tick(d, ang(v, VMAX), 63.6, 67.2, 0.32, INK)
    for v in tri:                                            # one long tick per hire
        tick(d, ang(v, VMAX), 57.0, 67.2, 0.95, INK)
    labels = [0, 6, 10, 15, 21, 28, 36, 45, 55, 66, 78, 91, 105, 120]
    f = bold(6.2)
    for v in labels:
        x, y = pt(50.0, ang(v, VMAX))
        text_c(d, (x, y), str(v), f, RED if v >= 78 else INK)
    # inner ring: people
    d.arc([C - 41.5 * PX, C - 41.5 * PX, C + 41.5 * PX, C + 41.5 * PX], ang(0, VMAX) - 90, ang(VMAX, VMAX) - 90,
          fill=GREY, width=int(0.3 * PX))
    fs = reg(3.6)
    for n, v in enumerate(tri, start=1):
        tick(d, ang(v, VMAX), 39.8, 41.5, 0.5, GREY)
        if n == 1 or n >= 4:
            x, y = pt(36.2, ang(v, VMAX))
            text_c(d, (x, y), str(n), fs, RED if n >= 13 else GREY)
    text_c(d, pt(27.0, 0), 'PEOPLE', reg(3.0), GREY)
    text_c(d, (C, C + 21.0 * PX), 'PATHWAYS', bold(4.4), INK)
    text_c(d, (C, C + 27.5 * PX), 'n(n−1)/2', reg(3.4), GREY)
    return img


def capacity():
    img, d = base()
    VMAX = 22.0
    d.arc([C - 67.2 * PX, C - 67.2 * PX, C + 67.2 * PX, C + 67.2 * PX], ang(0, VMAX) - 90, ang(VMAX, VMAX) - 90,
          fill=INK, width=int(0.35 * PX))
    for v in range(0, 23):
        tick(d, ang(v, VMAX), 63.0 if v % 2 else 57.0, 67.2, 0.32 if v % 2 else 0.95, INK)
    f = bold(6.2)
    for v in range(0, 23, 2):
        text_c(d, pt(50.0, ang(v, VMAX)), str(v), f, INK)
    text_c(d, (C, C + 21.0 * PX), 'PEOPLE', bold(4.4), INK)
    return img


def plate(word, seed):
    """Engraved two-ply laminate label (black over white), 72 x 18 mm."""
    W, H = 1440, 360                                         # 20 px/mm
    img = Image.new('RGB', (W, H), (20, 20, 19))
    d = ImageDraw.Draw(img)
    f = ImageFont.truetype(os.path.join(TYPE, 'B612-Bold.ttf'), 150)
    d.text((W / 2, H / 2 + 4), word, font=f, fill=(214, 212, 204), anchor='mm')
    # engraving is not crisp: soften, then a little roughness on the cut
    img = img.filter(ImageFilter.GaussianBlur(1.2))
    rng = np.random.default_rng(seed)
    a = np.asarray(img).astype(np.float32)
    a *= (0.93 + 0.07 * rng.random((H, W)))[..., None]
    # two screw holes are modelled; scuffs near the edges
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))


if __name__ == '__main__':
    for name, fn, seed in (('dial_coordination', coordination, 3), ('dial_capacity', capacity, 5)):
        im = age(fn(), seed).resize((2048, 2048), Image.LANCZOS)
        im.save(os.path.join(OUT, name + '.png'))
        print('wrote', name)
    plate('COORDINATION', 1).save(os.path.join(OUT, 'plate_coordination.png'))
    plate('CAPACITY', 2).save(os.path.join(OUT, 'plate_capacity.png'))
    print('wrote plates')
