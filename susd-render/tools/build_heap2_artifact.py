#!/usr/bin/env python3
"""Make the claude.ai artifact copy of The Heap v2: heap2-site-artifact/ from heap2-site/.
The artifact host wraps the page in its own skeleton, so index.html loses doctype/html/head/body/title/meta/icon. The
page must never navigate its own frame, so:
  - the head guard that adds a trailing slash (a location.replace) is dropped;
  - the form gets data-newtab (page.js then opens the Bootloader page in a NEW tab, synchronously inside the submit
    handler, and shows a visible link if the browser blocks it) plus target=_blank as the no-JS fallback;
  - the jump to #get does not rewrite the frame's URL (page.js skips history.replaceState in that mode).
assets/ is a real copy of heap2-site/assets (same CSS, JS, fonts, stills); the colours are tokens on :root, repeated
under the dark-scheme query and [data-theme="dark"], and body has an explicit background (all in heap2.css).
Run from anywhere: python3 susd-render/tools/build_heap2_artifact.py"""
import os, re, shutil
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'heap2-site')
DST = os.path.join(ROOT, 'heap2-site-artifact')
APPX = 'https://scaling-up-side-down.vercel.app/appendix#get'

s = open(os.path.join(SRC, 'index.html'), encoding='utf-8').read()

def sub1(old, new, text):
    assert old in text, old[:70]
    return text.replace(old, new, 1)

for tag in ['<!doctype html>\n', '<html lang="en">\n', '<head>\n', '</head>\n', '<body>\n', '</body>\n', '</html>\n']:
    s = sub1(tag, '', s)
s, n = re.subn(r'<title>[^<]*</title>\n', '', s); assert n == 1
s, n = re.subn(r'<meta [^>]*>[^\n]*\n', '', s); assert n >= 3
s = sub1('<link rel="icon" href="data:,">\n', '', s)
# no trailing-slash guard (a top-level navigation) in the framed copy; keep `var l=location;` (used below it)
s, n = re.subn(r"(var l=location;)if\(/\^https\?:\$/.*?return\}", r'\1', s, count=1); assert n == 1
s = sub1('<form class="form" id="get-form" action="' + APPX + '" method="get" novalidate>',
         '<form class="form" id="get-form" action="' + APPX + '" method="get" target="_blank" rel="noopener" data-newtab novalidate>', s)
s = sub1('''            <p class="msg-go" hidden>Taking you to the Bootloader page&#x2026;</p> <!-- // label -->''',
         '''            <p class="msg-go" hidden>Taking you to the Bootloader page&#x2026;</p> <!-- // label -->
            <p class="msg-blocked" hidden><a href="''' + APPX + '''" target="_blank" rel="noopener">Open the Bootloader page</a></p> <!-- // label -->''', s)
s = sub1('<p class="note" id="note">Opens the Bootloader page, where the file is sent by email.</p>',
         '<p class="note" id="note">Opens the Bootloader page in a new tab, where the file is sent by email.</p>', s)
for tag in ['!doctype', 'html', 'head', 'body', 'title']:
    assert not re.search(r'</?' + tag + r'[\s>]', s, re.I), tag
for bad in ['location.replace', 'l.replace(', 'location.assign']:
    assert bad not in s, bad
s = '<!-- The Heap v2, claude.ai artifact copy. Generated by susd-render/tools/build_heap2_artifact.py from heap2-site/index.html: do not edit by hand. -->\n' + s

os.makedirs(DST, exist_ok=True)
open(os.path.join(DST, 'index.html'), 'w', encoding='utf-8').write(s)
if os.path.islink(os.path.join(DST, 'assets')): os.unlink(os.path.join(DST, 'assets'))
shutil.rmtree(os.path.join(DST, 'assets'), ignore_errors=True)
shutil.copytree(os.path.join(SRC, 'assets'), os.path.join(DST, 'assets'))
print('wrote', os.path.join(DST, 'index.html'), 'and copied assets/')
