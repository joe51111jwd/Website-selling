#!/usr/bin/env python3
"""Make the claude.ai artifact copy of The Heap: heap-site-artifact/ from heap-site/.
The artifact host wraps the page in its own skeleton, so index.html loses doctype/html/head/body/title/meta; the page
must never navigate its own frame, so story-config gets "newtab": true (heap.js then opens the Bootloader page in a new
tab inside the submit gesture and scrolls in-page links by script), the form gets target=_blank, and the head guard
that adds a trailing slash is dropped. assets/ is a real copy of heap-site/assets (same CSS, JS, fonts, frames).
Run from anywhere: python3 susd-render/tools/build_heap_artifact.py"""
import os, re, shutil
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'heap-site')
DST = os.path.join(ROOT, 'heap-site-artifact')
APPX = 'https://scaling-up-side-down.vercel.app/appendix#get'

s = open(os.path.join(SRC, 'index.html'), encoding='utf-8').read()

def sub1(old, new, text):
    assert old in text, old[:60]
    return text.replace(old, new, 1)

for tag in ['<!doctype html>\n', '<html lang="en">\n', '<head>\n', '</head>\n', '<body>\n', '</body>\n', '</html>\n']:
    s = sub1(tag, '', s)
s = re.sub(r'<title>[^<]*</title>\n', '', s)
s = re.sub(r'<meta [^>]*>[^\n]*\n', '', s)
# no trailing-slash guard (a top-level navigation) in the framed copy
s = re.sub(r"var l=location;if\(.*?return\}", '', s, count=1)
s = sub1('<form class="form" id="get-form" action="' + APPX + '" method="get" novalidate>',
         '<form class="form" id="get-form" action="' + APPX + '" method="get" target="_blank" rel="noopener" novalidate>', s)
s = sub1('''              <p class="msg-go" hidden>Taking you to the Bootloader page&#x2026;</p> <!-- // label -->''',
         '''              <p class="msg-go" hidden>Taking you to the Bootloader page&#x2026;</p> <!-- // label -->
              <p class="msg-blocked" hidden><a href="''' + APPX + '''" target="_blank" rel="noopener">Open the Bootloader page</a></p> <!-- // label -->''', s)
s = sub1('<script type="application/json" id="story-config">{"len":1200,"F":40,"fc":10}</script>',
         '<script type="application/json" id="story-config">{"len":1200,"F":40,"fc":10,"newtab":true}</script>', s)
s = '<!-- The Heap, claude.ai artifact copy. Generated by susd-render/tools/build_heap_artifact.py from heap-site/index.html: do not edit by hand. -->\n' + s

os.makedirs(DST, exist_ok=True)
open(os.path.join(DST, 'index.html'), 'w', encoding='utf-8').write(s)
if os.path.islink(os.path.join(DST, 'assets')): os.unlink(os.path.join(DST, 'assets'))
shutil.rmtree(os.path.join(DST, 'assets'), ignore_errors=True)
shutil.copytree(os.path.join(SRC, 'assets'), os.path.join(DST, 'assets'))
print('wrote', os.path.join(DST, 'index.html'), 'and copied assets/')
