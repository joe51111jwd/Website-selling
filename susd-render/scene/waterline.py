    while i < len(argv):
        k = argv[i].lstrip('-')
        if k not in a and k not in TUNE:
            raise SystemExit(f'waterline.py: unknown option --{k} (see TUNE and DEFAULTS_A in scene/waterline.py)')
        v = argv[i + 1] if i + 1 < len(argv) else '1'
        passed.add(k)
        ref = a[k] if k in a else TUNE[k]
        if k in A_STR or k in TUNE_STR:
            pass
        elif isinstance(ref, int) and not isinstance(ref, bool):
            v = int(float(v))
        else:
            try:
                v = float(v)
            except ValueError:
                raise SystemExit(f'waterline.py: --{k} needs a number, got {v!r}')
        if k in a:
            a[k] = v
        else:
            TUNE[k] = v
        i += 2
    return a, passed


