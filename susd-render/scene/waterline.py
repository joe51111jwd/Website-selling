def hull_paint(name, base_srgb, rough, wet_obj, hw_obj=None, boot_z=None, wear=None, fresh=False, tone=(0.93, 1.06)):
    """Ship's hull paint on steel plate: the base colour, a scanned roughness breakup (blue_metal_plate), orange
    peel and the plate's own dents (its scanned normal, faint), the plates dished between internal frames 0.7 m
    apart, a tone and scan offset per plate (Object Info Random), wet and glossy above the water, the splash zone,
    a pale salt ring at the highest water, and (lower hull) red-oxide antifouling below the boot-top line.
    wear = (mask_img, rect, ref): fender scrapes and rust, mixed toward primer grey and rust brown."""
    m = bpy.data.materials.new(name); m.use_nodes = True
    nt = m.node_tree; bsdf = nt.nodes['Principled BSDF']
    bsdf.inputs['Coat Weight'].default_value = 0.0
    tc = nt.nodes.new('ShaderNodeTexCoord')
    oi = nt.nodes.new('ShaderNodeObjectInfo')
    # per plate: offset the scan by the object's random number (no two plates show the same patch)
    off = nt.nodes.new('ShaderNodeCombineXYZ')
    L.link(nt, _m(nt, 'MULTIPLY', oi.outputs['Random'], 7.31), off.inputs['X'])
    L.link(nt, _m(nt, 'MULTIPLY', oi.outputs['Random'], 3.17), off.inputs['Z'])
    vadd = nt.nodes.new('ShaderNodeVectorMath'); vadd.operation = 'ADD'
    L.link(nt, tc.outputs['Object'], vadd.inputs[0]); L.link(nt, off.outputs['Vector'], vadd.inputs[1])
    mp = nt.nodes.new('ShaderNodeMapping'); mp.inputs['Scale'].default_value = (0.35, 0.35, 0.35)
    L.link(nt, vadd.outputs['Vector'], mp.inputs['Vector'])
    f = L._maps('blue_metal_plate')
    r_img = L._img(nt, f['rough'], True); L.link(nt, mp.outputs['Vector'], r_img.inputs['Vector'])
    rr = nt.nodes.new('ShaderNodeMapRange'); L.link(nt, r_img.outputs['Color'], rr.inputs['Value'])
    rr.inputs['To Min'].default_value = rough - 0.12; rr.inputs['To Max'].default_value = rough + 0.10
    L.link(nt, rr.outputs['Result'], bsdf.inputs['Roughness'])
    n_img = L._img(nt, f['nor_gl'], True); L.link(nt, mp.outputs['Vector'], n_img.inputs['Vector'])
    nm = nt.nodes.new('ShaderNodeNormalMap'); nm.inputs['Strength'].default_value = 0.25
    L.link(nt, n_img.outputs['Color'], nm.inputs['Color'])
    # orange peel
