XMIN_H = -12.0


def streak(arr, ppm, x0, z0, zbase, width, length, strength, rng, wander=0.01, xmin=None):
    """Adds a streak running DOWN from (x0, z0) into the mask `arr` (h, w): rust weeping from a fixing."""
    xmin = XMIN_H if xmin is None else xmin
    h, w_all = arr.shape[:2]
    reach = width * 3.5 * 2.2 + 0.06
    c0 = max(0, int((x0 - reach - xmin) * ppm)); c1 = min(w_all, int((x0 + reach - xmin) * ppm) + 1)
    if c1 <= c0:
        return
    xs = (np.arange(c0, c1) + 0.5) / ppm + xmin
    zs = (np.arange(h) + 0.5) / ppm + zbase
    d = z0 - zs[:, None]
    along = np.clip(d / length, 0, None)
    fall = np.where(d >= 0, np.exp(-3.0 * along) * (1 - np.clip(along - 0.85, 0, 1) * 6).clip(0, 1), 0.0)
    wob = np.interp(zs, np.linspace(zs[0], zs[-1], 24), rng.normal(0, wander, 24))[:, None]
    wd = width * (1 + 1.2 * along)
    across = np.exp(-(((xs[None, :] - x0 - wob) / wd) ** 2))
    brk = np.interp(zs, np.linspace(zs[0], zs[-1], 160), rng.uniform(0.55, 1.0, 160))[:, None]
    arr[:, c0:c1] = np.maximum(arr[:, c0:c1], strength * fall * across * brk)


def scrapes(arr, ppm, zbase, xmin, n, zlo, zhi, rng, avoid=None):
    """Fender scrapes into the mask: short horizontal rubs (0.2-1.4 m long, 1-4 cm tall), ragged, broken."""
    h, w = arr.shape
    for _ in range(n):
        x0 = rng.uniform(xmin + 0.5, xmin + w / ppm - 0.5)
        z0 = rng.uniform(zlo, zhi)
        if avoid and avoid[0] < x0 < avoid[1] and avoid[2] < z0 < avoid[3]:
            continue
        ln = rng.uniform(0.2, 1.4); th = rng.uniform(0.008, 0.04)
        c0 = max(0, int((x0 - xmin) * ppm)); c1 = min(w, int((x0 + ln - xmin) * ppm))
        r0 = max(0, int((z0 - th - zbase) * ppm)); r1 = min(h, int((z0 + th - zbase) * ppm) + 1)
        if c1 <= c0 or r1 <= r0:
            continue
        xs = np.linspace(0, 1, c1 - c0)
        prof = np.sin(np.pi * xs) ** 0.4 * rng.uniform(0.5, 1.0)
        zz = (np.arange(r0, r1) + 0.5) / ppm + zbase
        across = np.exp(-(((zz - z0) / th) ** 2))[:, None]
        noise = rng.uniform(0.3, 1.0, (r1 - r0, c1 - c0))
        noise = (noise > 0.45) * noise
        arr[r0:r1, c0:c1] = np.maximum(arr[r0:r1, c0:c1], prof[None, :] * across * noise)


