def scar_ring(m, hw_obj, width=0.07, mul_srgb=(0.50, 0.48, 0.38), amount=0.9, scale=6.0):
    """The flood scar: a narrow silt-and-scum line left where the water stood longest at its highest
    (a bathtub ring), ragged along its length. Sits on top of add_stain's softer silt below the line."""
    nt = m.node_tree
    bsdf = nt.nodes['Principled BSDF']
    src = bsdf.inputs['Base Color'].links[0].from_socket if bsdf.inputs['Base Color'].links else None
    tc = nt.nodes.new('ShaderNodeTexCoord'); tc.object = hw_obj
    sep = nt.nodes.new('ShaderNodeSeparateXYZ'); L.link(nt, tc.outputs['Object'], sep.inputs['Vector'])
    g = nt.nodes.new('ShaderNodeNewGeometry')
