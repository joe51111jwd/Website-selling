    blender_kern.apply(cu, fp)
    cu.extrude = max(depth / 2 - bevel, 0.0001) if depth > 0 else 0.0
    cu.bevel_depth = bevel
    cu.bevel_resolution = 2
    cu.resolution_u = res_u
