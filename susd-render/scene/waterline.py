def np_image(name, arr):
    """arr: (h, w, 3) float32, row 0 = bottom. -> packed float Blender image (Non-Color data)."""
    h, w = arr.shape[:2]
    img = bpy.data.images.new(name, w, h, float_buffer=True, is_data=True)
    px = np.ones((h, w, 4), np.float32)
    px[..., :3] = arr
    img.pixels.foreach_set(px.ravel())
    img.pack()
    return img


def planar_lookup(nt, img, x0, x1, z0, z1, ref=None):
    """Image sampled over the XZ rectangle [x0,x1] x [z0,z1]: in world coordinates, or relative to `ref`
    (an empty) so the map travels with the moving parts."""
    if ref is None:
        g = nt.nodes.new('ShaderNodeNewGeometry'); vec = g.outputs['Position']
    else:
        tc = nt.nodes.new('ShaderNodeTexCoord'); tc.object = ref; vec = tc.outputs['Object']
    sep = nt.nodes.new('ShaderNodeSeparateXYZ'); L.link(nt, vec, sep.inputs['Vector'])
    u = nt.nodes.new('ShaderNodeMapRange'); u.clamp = True
    u.inputs['From Min'].default_value = x0; u.inputs['From Max'].default_value = x1
    L.link(nt, sep.outputs['X'], u.inputs['Value'])
    v = nt.nodes.new('ShaderNodeMapRange'); v.clamp = True
    v.inputs['From Min'].default_value = z0; v.inputs['From Max'].default_value = z1
    L.link(nt, sep.outputs['Z'], v.inputs['Value'])
    cm = nt.nodes.new('ShaderNodeCombineXYZ')
    L.link(nt, u.outputs['Result'], cm.inputs['X']); L.link(nt, v.outputs['Result'], cm.inputs['Y'])
    ti = nt.nodes.new('ShaderNodeTexImage'); ti.image = img; ti.extension = 'EXTEND'; ti.interpolation = 'Linear'
    L.link(nt, cm.outputs['Vector'], ti.inputs['Vector'])
    return ti.outputs['Color']


def _m(nt, op, a, b=None, c=None):
    """One Math node: inputs may be sockets or numbers."""
    n = nt.nodes.new('ShaderNodeMath'); n.operation = op
    for i, v in enumerate((a, b, c)):
        if v is None:
            continue
        if isinstance(v, (int, float)):
            n.inputs[i].default_value = v
        else:
            L.link(nt, v, n.inputs[i])
    return n.outputs[0]


def mix_into(m, inp, fac_sock, value, kind='RGBA', blend='MIX'):
    """Mix the Principled input `inp` toward `value` (a colour tuple or a float) by fac_sock."""
    nt = m.node_tree; bsdf = nt.nodes['Principled BSDF']
    src = bsdf.inputs[inp].links[0].from_socket if bsdf.inputs[inp].links else None
    if kind == 'RGBA':
        mx, f_, a_, b_, r_ = L.mix(nt, 'RGBA', blend)
        b_.default_value = (*value, 1) if len(value) == 3 else value
    else:
        mx, f_, a_, b_, r_ = L.mix(nt, 'FLOAT')
        b_.default_value = value
    if isinstance(fac_sock, (int, float)):
        f_.default_value = fac_sock
    else:
        L.link(nt, fac_sock, f_)
    if src is not None:
        L.link(nt, src, a_)
    else:
        a_.default_value = bsdf.inputs[inp].default_value
    L.link(nt, r_, bsdf.inputs[inp])


