def split_islands(me):
    """One group per letter: weld coincident vertices, find connected pieces, then merge pieces whose
    bounding boxes coincide (Blender's text-to-mesh can leave a letter's caps apart from its sides).
    -> list of (verts array, faces list)."""
    bm = bmesh.new(); bm.from_mesh(me)
    bmesh.ops.remove_doubles(bm, verts=bm.verts[:], dist=1e-6)
    bm.to_mesh(me); bm.free()
    n = len(me.vertices)
    co = np.empty(n * 3, np.float32); me.vertices.foreach_get('co', co); co = co.reshape(-1, 3)
    parent = list(range(n))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    for e in me.edges:
        a, b = find(e.vertices[0]), find(e.vertices[1])
        if a != b:
            parent[a] = b
    comp = {}
    for i in range(n):
        comp.setdefault(find(i), []).append(i)
    pieces = list(comp.values())
    boxes = [(co[ix, 0].min(), co[ix, 0].max(), co[ix, 2].min(), co[ix, 2].max()) for ix in pieces]
    owner = list(range(len(pieces)))

    def fo(a):
        while owner[a] != a:
            a = owner[a]
        return a
    for i in range(len(pieces)):
        for j in range(i + 1, len(pieces)):
            a, b = boxes[i], boxes[j]
            ox = min(a[1], b[1]) - max(a[0], b[0]); oz = min(a[3], b[3]) - max(a[2], b[2])
            if ox <= 0 or oz <= 0:
                continue
            small = min((a[1] - a[0]) * (a[3] - a[2]), (b[1] - b[0]) * (b[3] - b[2])) + 1e-9
            if ox * oz / small > 0.7:
                ri, rj = fo(i), fo(j)
                if ri != rj:
                    owner[rj] = ri
    groups = {}
    for i, ix in enumerate(pieces):
        groups.setdefault(fo(i), []).extend(ix)
    groups = sorted(groups.values(), key=lambda ix: co[ix, 0].mean())
    vg = {}
    for gi, ix in enumerate(groups):
        for i in ix:
            vg[i] = gi
    faces = [[] for _ in groups]
    for p in me.polygons:
        faces[vg[p.vertices[0]]].append(list(p.vertices))
    out = []
    for gi, ix in enumerate(groups):
        remap = {old: k for k, old in enumerate(ix)}
        out.append((co[ix], [[remap[v] for v in f] for f in faces[gi]]))
    return out


