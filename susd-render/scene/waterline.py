def bolt_weeps(nt, col, tc):
    """Painted-over bolt heads and, under some of them, a short rust run (3-6 cm: review round 2)."""
    sep = nt.nodes.new('ShaderNodeSeparateXYZ'); L.link(nt, tc.outputs['Object'], sep.inputs['Vector'])
    X, Z = sep.outputs['X'], sep.outputs['Z']
    at = {}
    for k in ('bx', 'bz', 'weep_l', 'weep_r'):
        a = nt.nodes.new('ShaderNodeAttribute'); a.attribute_type = 'OBJECT'; a.attribute_name = k
        at[k] = a.outputs['Fac']
    brk = nt.nodes.new('ShaderNodeTexNoise'); brk.inputs['Scale'].default_value = 30.0; brk.inputs['Detail'].default_value = 4.0
    mpz = nt.nodes.new('ShaderNodeMapping'); mpz.inputs['Scale'].default_value = (3.0, 3.0, 0.35)
    L.link(nt, tc.outputs['Object'], mpz.inputs['Vector']); L.link(nt, mpz.outputs['Vector'], brk.inputs['Vector'])
    brk_v = _m(nt, 'MULTIPLY_ADD', brk.outputs['Fac'], 1.6, -0.35)
    head_total, weep_total = None, None
    for side, wk in ((-1.0, 'weep_l'), (1.0, 'weep_r')):
        dx = _m(nt, 'SUBTRACT', X, _m(nt, 'MULTIPLY', at['bx'], side))
        dz = _m(nt, 'SUBTRACT', Z, at['bz'])
        r = _m(nt, 'SQRT', _m(nt, 'ADD', _m(nt, 'MULTIPLY', dx, dx), _m(nt, 'MULTIPLY', dz, dz)))
        hd = nt.nodes.new('ShaderNodeMapRange'); hd.interpolation_type = 'SMOOTHSTEP'
        hd.inputs['From Min'].default_value = 0.0062; hd.inputs['From Max'].default_value = 0.0048
        L.link(nt, r, hd.inputs['Value'])
        along = _m(nt, 'MAXIMUM', _m(nt, 'MULTIPLY', dz, -1.0), 0.0)
        w = _m(nt, 'MULTIPLY_ADD', along, 0.05, 0.003)
        q = _m(nt, 'DIVIDE', dx, w)
        across = _m(nt, 'EXPONENT', _m(nt, 'MULTIPLY', _m(nt, 'MULTIPLY', q, q), -1.0))
        fall = _m(nt, 'EXPONENT', _m(nt, 'MULTIPLY', along, -28.0))                  # fades over ~4 cm
        below = _m(nt, 'GREATER_THAN', _m(nt, 'MULTIPLY', dz, -1.0), -0.004)
        wv = _m(nt, 'MULTIPLY', _m(nt, 'MULTIPLY', _m(nt, 'MULTIPLY', across, fall), below), at[wk])
        wv = _m(nt, 'MULTIPLY', wv, brk_v)
        head_total = hd.outputs['Result'] if head_total is None else _m(nt, 'MAXIMUM', head_total, hd.outputs['Result'])
        weep_total = wv if weep_total is None else _m(nt, 'MAXIMUM', weep_total, wv)
    has = _m(nt, 'GREATER_THAN', at['bz'], -0.5)
    head_total = _m(nt, 'MULTIPLY', head_total, has)
    weep_total = _m(nt, 'MINIMUM', _m(nt, 'MULTIPLY', weep_total, has), 1.0)
    mw, f1, a1, b1, r1 = L.mix(nt, 'RGBA', 'MULTIPLY')
    L.link(nt, _m(nt, 'MULTIPLY', weep_total, 0.6), f1); L.link(nt, col, a1)
    b1.default_value = (*L.srgb_to_lin((0.62, 0.42, 0.28)), 1)
    mh, f2, a2, b2, r2 = L.mix(nt, 'RGBA', 'MULTIPLY')
    L.link(nt, _m(nt, 'MULTIPLY', head_total, 0.45), f2); L.link(nt, r1, a2)
    b2.default_value = (*L.srgb_to_lin((0.60, 0.55, 0.50)), 1)
    return r2


