def split_islands(me):
    """One group per letter: weld coincident vertices, find connected pieces, then merge pieces whose bounding
    boxes coincide. -> list of (verts array, faces list)."""
    bm = bmesh.new(); bm.from_mesh(me)
    bmesh.ops.remove_doubles(bm, verts=bm.verts[:], dist=1e-6)
    bm.to_mesh(me); bm.free()
    n = len(me.vertices)
    co = np.empty(n * 3, np.float32); me.vertices.foreach_get('co', co); co = co.reshape(-1, 3)
    parent = list(range(n))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    for e in me.edges:
        a, b = find(e.vertices[0]), find(e.vertices[1])
        if a != b:
            parent[a] = b
    comp = {}
    for i in range(n):
        comp.setdefault(find(i), []).append(i)
    pieces = list(comp.values())
    boxes = [(co[ix, 0].min(), co[ix, 0].max(), co[ix, 2].min(), co[ix, 2].max()) for ix in pieces]
    owner = list(range(len(pieces)))

    def fo(a):
        while owner[a] != a:
            a = owner[a]
        return a
    for i in range(len(pieces)):
        for j in range(i + 1, len(pieces)):
            a, b = boxes[i], boxes[j]
            ox = min(a[1], b[1]) - max(a[0], b[0]); oz = min(a[3], b[3]) - max(a[2], b[2])
            if ox <= 0 or oz <= 0:
                continue
            small = min((a[1] - a[0]) * (a[3] - a[2]), (b[1] - b[0]) * (b[3] - b[2])) + 1e-9
            if ox * oz / small > 0.7:
                ri, rj = fo(i), fo(j)
                if ri != rj:
                    owner[rj] = ri
    groups = {}
    for i, ix in enumerate(pieces):
        groups.setdefault(fo(i), []).extend(ix)
    groups = sorted(groups.values(), key=lambda ix: co[ix, 0].mean())
    vg = {}
    for gi, ix in enumerate(groups):
        for i in ix:
            vg[i] = gi
    faces = [[] for _ in groups]
    for p in me.polygons:
        faces[vg[p.vertices[0]]].append(list(p.vertices))
    out = []
    for gi, ix in enumerate(groups):
        remap = {old: k for k, old in enumerate(ix)}
        out.append((co[ix], [[remap[v] for v in f] for f in faces[gi]]))
    return out


def mesh_bounds(me):
    co = np.empty(len(me.vertices) * 3, np.float32); me.vertices.foreach_get('co', co); co = co.reshape(-1, 3)
    return co[:, 0].min(), co[:, 0].max(), co[:, 2].min(), co[:, 2].max()


def flat_ring(name, cx, cz, r_out, r_in, y, mat, seg=96):
    me = bpy.data.meshes.new(name); bm = bmesh.new()
    outer = [bm.verts.new((cx + r_out * math.cos(2 * math.pi * i / seg), y, cz + r_out * math.sin(2 * math.pi * i / seg))) for i in range(seg)]
    inner = [bm.verts.new((cx + r_in * math.cos(2 * math.pi * i / seg), y, cz + r_in * math.sin(2 * math.pi * i / seg))) for i in range(seg)]
    for i in range(seg):
        j = (i + 1) % seg
        bm.faces.new((outer[i], outer[j], inner[j], inner[i]))
    bm.normal_update(); bm.to_mesh(me); bm.free()
    return L.obj_from_mesh(name, me, mat)


def flat_text(name, text, cap, x_left, z_base, y, mat, align='LEFT'):
    """Painted text (no depth) in the mark face, its cap height `cap`, baseline z_base."""
    me = text_mesh(text, cap / 0.70, 0.0, 0.0, name=name, font=MARK_FONT)
    b = mesh_bounds(me)
    dx = (x_left - b[0]) if align == 'LEFT' else (x_left - b[1])
    for v in me.vertices:
        v.co.x += dx; v.co.z += z_base; v.co.y = y
    ob = L.obj_from_mesh(name, me, mat)
    return ob, mesh_bounds(me)


