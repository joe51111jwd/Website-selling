# Anchors: where things land in the frame (normalised 0-1, y down), for the page (brief 7.6)
# --------------------------------------------------------------------------------------------
def anchors():
    from bpy_extras.object_utils import world_to_camera_view
    bpy.context.view_layer.update()

    # The compositor finish zooms the frame (lens Fit for the lateral colour, then the 1.2 % crop), so
    # project through the camera and then apply the same zoom about the centre (review round 1: the
    # anchors were up to ~6 px off at the frame edges). ZOOM is measured: scene/measure_zoom.py.
    k = ZOOM if (not A['nopost'] and TUNE['dispersion'] > 0) else 1.0

    def P(p):
        c = world_to_camera_view(sc, cam, Vector(p))
        return [round(0.5 + (c.x - 0.5) * k, 4), round(0.5 + ((1 - c.y) - 0.5) * k, 4)]
    xs, ys = [], []
    for ob in letters:
        for corner in ob.bound_box:
            q = P(ob.matrix_world @ Vector(corner))
            xs.append(q[0]); ys.append(q[1])
    words = [round(min(xs), 4), round(min(ys), 4), round(max(xs), 4), round(max(ys), 4)]
    stencil = None
    if STENCIL is not None:
        x0_, x1_, z0_, z1_, y_ = STENCIL_BOX
        a_, b_ = P((x0_, y_, z1_)), P((x1_, y_, z0_))
        stencil = [a_[0], a_[1], b_[0], b_[1]]
    return dict(id=A['label'] or KEY, state=KEY, between=A['between'] or None, t=T, frame=FRAME, name=ST['name'],
                layout='phone' if PHONE else 'desktop', cam=FR['cam'],
                n=None if ST['n'] is None else round(ST['n'], 3), p=None if ST['n'] is None else round(pathways(ST['n']), 1),
                level=round(ST['water'], 3), deck=round(ST['deck'], 3), signal=ST['signal'], words=words, stencil=stencil,
                zoom=k,
                waterY=P((0.0, -LAND_D if WATER < D0 else -0.02, WATER))[1], deckY=P((0.0, PANEL_Y, DECK))[1],
                deckX=[P((-PANEL_W / 2, PANEL_Y, DECK))[0], P((PANEL_W / 2, PANEL_Y, DECK))[0]], sunEl=round(sun_el, 2),
                signalXY=P((SIGNAL_X, -0.16, SIG_Z)) if not PHONE else None,
                mark12=P((MARK_X, FY, Z12)), gaugeX=P((GAUGE_X, -0.03, 1.0))[0],
                scarY=P((0.0, -0.02, HW_WALL))[1] if HISTK['hw_wall'] > ST['water'] + 1e-6 else None,
                focus=[round((words[0] + words[2]) / 2, 4), round((words[1] + words[3]) / 2, 4)],
                metres=dict(H=round(H, 4), cap=CAP, D0=round(D0, 4), water=round(WATER, 4), deck=round(DECK, 4),
                            block_w=round(float(BLOCK_W), 4), cam=[round(v, 3) for v in cam.location], focal=focal,
                            shift_y=round(shift_y, 4), frame_w=round(frame_w, 3), frame_h=round(frame_h, 3)))


