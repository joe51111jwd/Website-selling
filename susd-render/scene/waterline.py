def box_local(name, sx, sy, sz, loc, mat=None, bevel=0.0, segments=3):
    """A box sized (sx, sy, sz) whose mesh is centred on its object origin (object-space textures travel with it)."""
    me = bpy.data.meshes.new(name)
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    for v in bm.verts:
        v.co = Vector((v.co.x * sx, v.co.y * sy, v.co.z * sz))
    if bevel > 0:
        bmesh.ops.bevel(bm, geom=bm.edges[:], offset=bevel, segments=segments, affect='EDGES', profile=0.5)
    bm.to_mesh(me); bm.free()
    if bevel > 0:
        L._sharp_by_angle(me, 50 if segments > 1 else 30)
    ob = L.obj_from_mesh(name, me, mat)
    ob.location = loc
    return ob


def boxes_mesh(name, boxes, mat, bevel=0.0, segments=2):
    """Many small boxes (cx, cy, cz, sx, sy, sz) as one mesh (the weld beads)."""
    bm = bmesh.new()
    for (cx, cy, cz, sx, sy, sz) in boxes:
        r = bmesh.ops.create_cube(bm, size=1.0)
        for v in r['verts']:
            v.co = Vector((cx + v.co.x * sx, cy + v.co.y * sy, cz + v.co.z * sz))
    if bevel > 0:
        bmesh.ops.bevel(bm, geom=bm.edges[:], offset=bevel, segments=segments, affect='EDGES', profile=0.5)
    me = bpy.data.meshes.new(name); bm.to_mesh(me); bm.free()
    for p in me.polygons:
        p.use_smooth = True
    return L.obj_from_mesh(name, me, mat)


def text_mesh(text, size, depth, bevel, res_u=12, name='line', font=None):
    """A face, kerned, tracked 1.03, as a mesh standing up in XZ: front face at y = 0, body back to y = +depth,
    baseline z = 0, centred on x = 0."""
    fp = font or FONT
