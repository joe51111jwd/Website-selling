def salt_ring(m, hw_obj, width=0.07, amount=0.26, film=0.08):
    """Where the water stood highest a pale ring of dried salt and scum, ragged along its length, and a faint
    dull film below it (on dark paint a high-water mark is lighter, not darker)."""
