def _m(nt, op, a, b=None, c=None):
    """One Math node: inputs may be sockets or numbers."""
    n = nt.nodes.new('ShaderNodeMath'); n.operation = op
    for i, v in enumerate((a, b, c)):
        if v is None:
            continue
        if isinstance(v, (int, float)):
            n.inputs[i].default_value = v
        else:
            L.link(nt, v, n.inputs[i])
    return n.outputs[0]


def bolt_weeps(nt, col, tc):
    """Painted-over bolt heads and the rust that has run down the face below them (letter object space:
    x across, z up, metres; the mesh is centred on the letter's box)."""
    sep = nt.nodes.new('ShaderNodeSeparateXYZ'); L.link(nt, tc.outputs['Object'], sep.inputs['Vector'])
    X, Z = sep.outputs['X'], sep.outputs['Z']
    at = {}
    for k in ('bx', 'bz', 'weep_l', 'weep_r'):
        a = nt.nodes.new('ShaderNodeAttribute'); a.attribute_type = 'OBJECT'; a.attribute_name = k
        at[k] = a.outputs['Fac']
    brk = nt.nodes.new('ShaderNodeTexNoise'); brk.inputs['Scale'].default_value = 30.0; brk.inputs['Detail'].default_value = 4.0
    mpz = nt.nodes.new('ShaderNodeMapping'); mpz.inputs['Scale'].default_value = (3.0, 3.0, 0.35)   # runs: long in z
    L.link(nt, tc.outputs['Object'], mpz.inputs['Vector']); L.link(nt, mpz.outputs['Vector'], brk.inputs['Vector'])
    brk_v = _m(nt, 'MULTIPLY_ADD', brk.outputs['Fac'], 1.6, -0.35)
    head_total, weep_total = None, None
    for side, wk in ((-1.0, 'weep_l'), (1.0, 'weep_r')):
        dx = _m(nt, 'SUBTRACT', X, _m(nt, 'MULTIPLY', at['bx'], side))
        dz = _m(nt, 'SUBTRACT', Z, at['bz'])
        r = _m(nt, 'SQRT', _m(nt, 'ADD', _m(nt, 'MULTIPLY', dx, dx), _m(nt, 'MULTIPLY', dz, dz)))
        hd = nt.nodes.new('ShaderNodeMapRange'); hd.interpolation_type = 'SMOOTHSTEP'
        hd.inputs['From Min'].default_value = 0.0068; hd.inputs['From Max'].default_value = 0.0052
        L.link(nt, r, hd.inputs['Value'])
        along = _m(nt, 'MAXIMUM', _m(nt, 'MULTIPLY', dz, -1.0), 0.0)               # metres below the bolt
        w = _m(nt, 'MULTIPLY_ADD', along, 0.05, 0.0035)                              # widens as it runs
        q = _m(nt, 'DIVIDE', dx, w)
        across = _m(nt, 'EXPONENT', _m(nt, 'MULTIPLY', _m(nt, 'MULTIPLY', q, q), -1.0))
        fall = _m(nt, 'EXPONENT', _m(nt, 'MULTIPLY', along, -14.0))                  # fades over ~7 cm
        below = _m(nt, 'GREATER_THAN', _m(nt, 'MULTIPLY', dz, -1.0), -0.004)
        wv = _m(nt, 'MULTIPLY', _m(nt, 'MULTIPLY', _m(nt, 'MULTIPLY', across, fall), below), at[wk])
        wv = _m(nt, 'MULTIPLY', wv, brk_v)
        head_total = hd.outputs['Result'] if head_total is None else _m(nt, 'MAXIMUM', head_total, hd.outputs['Result'])
        weep_total = wv if weep_total is None else _m(nt, 'MAXIMUM', weep_total, wv)
    has = _m(nt, 'GREATER_THAN', at['bz'], -0.5)          # letters with no bolts (bz = -1) stay clean
    head_total = _m(nt, 'MULTIPLY', head_total, has)
    weep_total = _m(nt, 'MINIMUM', _m(nt, 'MULTIPLY', weep_total, has), 1.0)
    mw, f1, a1, b1, r1 = L.mix(nt, 'RGBA', 'MULTIPLY')
    L.link(nt, _m(nt, 'MULTIPLY', weep_total, 0.75), f1); L.link(nt, col, a1)
    b1.default_value = (*L.srgb_to_lin((0.60, 0.40, 0.27)), 1)
    mh, f2, a2, b2, r2 = L.mix(nt, 'RGBA', 'MULTIPLY')
    L.link(nt, _m(nt, 'MULTIPLY', head_total, 0.55), f2); L.link(nt, r1, a2)
    b2.default_value = (*L.srgb_to_lin((0.55, 0.45, 0.38)), 1)
    return r2


def splash_band(m, level_obj, band=0.08, dark=0.75, rough=0.15):
    """The splash zone: the 8 cm just above the water, darker and glossier (with the 12 cm wet top already
    applied, 0.6 of dry), so where the water meets the letters and the panel there is visible contact
    (review round 1, K3). Above the water only: drowned paint is not darkened twice."""
    nt = m.node_tree
    bsdf = nt.nodes['Principled BSDF']
    tc = nt.nodes.new('ShaderNodeTexCoord'); tc.object = level_obj
    sep = nt.nodes.new('ShaderNodeSeparateXYZ'); L.link(nt, tc.outputs['Object'], sep.inputs['Vector'])
    nz = nt.nodes.new('ShaderNodeTexNoise'); nz.inputs['Scale'].default_value = 14.0; nz.inputs['Detail'].default_value = 6.0
    g = nt.nodes.new('ShaderNodeNewGeometry'); L.link(nt, g.outputs['Position'], nz.inputs['Vector'])
    off = nt.nodes.new('ShaderNodeMath'); off.operation = 'MULTIPLY_ADD'
    L.link(nt, nz.outputs['Fac'], off.inputs[0]); off.inputs[1].default_value = band * 0.8; off.inputs[2].default_value = -band * 0.4
    zz = nt.nodes.new('ShaderNodeMath'); zz.operation = 'SUBTRACT'
    L.link(nt, sep.outputs['Z'], zz.inputs[0]); L.link(nt, off.outputs[0], zz.inputs[1])
    top = nt.nodes.new('ShaderNodeMapRange'); top.interpolation_type = 'SMOOTHSTEP'
    top.inputs['From Min'].default_value = band; top.inputs['From Max'].default_value = 0.0
    L.link(nt, zz.outputs[0], top.inputs['Value'])
    bot = nt.nodes.new('ShaderNodeMapRange')
    bot.inputs['From Min'].default_value = -0.03; bot.inputs['From Max'].default_value = 0.0
    L.link(nt, sep.outputs['Z'], bot.inputs['Value'])
    msk = nt.nodes.new('ShaderNodeMath'); msk.operation = 'MULTIPLY'
    L.link(nt, top.outputs['Result'], msk.inputs[0]); L.link(nt, bot.outputs['Result'], msk.inputs[1])
    for inp, kind, val in (('Base Color', 'RGBA', dark), ('Roughness', 'FLOAT', rough)):
        src = bsdf.inputs[inp].links[0].from_socket if bsdf.inputs[inp].links else None
        if kind == 'RGBA':
            mx, f_, a_, b_, r_ = L.mix(nt, 'RGBA', 'MULTIPLY'); b_.default_value = (val, val, val, 1)
        else:
            mx, f_, a_, b_, r_ = L.mix(nt, 'FLOAT'); b_.default_value = val
        L.link(nt, msk.outputs[0], f_)
        if src is not None:
            L.link(nt, src, a_)
        else:
            a_.default_value = bsdf.inputs[inp].default_value
        L.link(nt, r_, bsdf.inputs[inp])
    return m


