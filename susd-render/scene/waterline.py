def insert_multiply(m, color_socket_fn, label='mul'):
    """Multiply the material's current base colour by a colour socket made by color_socket_fn(nt)."""
    nt = m.node_tree
    bsdf = nt.nodes['Principled BSDF']
    src = bsdf.inputs['Base Color'].links[0].from_socket if bsdf.inputs['Base Color'].links else None
    mx, f_, a_, b_, r_ = L.mix(nt, 'RGBA', 'MULTIPLY')
    f_.default_value = 1.0
    if src is not None:
        L.link(nt, src, a_)
    else:
        a_.default_value = bsdf.inputs['Base Color'].default_value
    L.link(nt, color_socket_fn(nt), b_)
    L.link(nt, r_, bsdf.inputs['Base Color'])
    return m


def np_image(name, arr):
    """arr: (h, w, 3) float32, row 0 = bottom. -> packed float Blender image (Non-Color data)."""
    h, w = arr.shape[:2]
    img = bpy.data.images.new(name, w, h, float_buffer=True, is_data=True)
    px = np.ones((h, w, 4), np.float32)
    px[..., :3] = arr
    img.pixels.foreach_set(px.ravel())
    img.pack()
    return img


def planar_lookup(nt, img, x0, x1, z0, z1, coords='Object'):
    """Image sampled over the XZ rectangle [x0,x1] x [z0,z1] in object (or world) coordinates."""
    if coords == 'World':
        g = nt.nodes.new('ShaderNodeNewGeometry'); vec = g.outputs['Position']
    else:
        tc = nt.nodes.new('ShaderNodeTexCoord'); vec = tc.outputs['Object']
    sep = nt.nodes.new('ShaderNodeSeparateXYZ'); L.link(nt, vec, sep.inputs['Vector'])
    u = nt.nodes.new('ShaderNodeMapRange'); u.clamp = True
    u.inputs['From Min'].default_value = x0; u.inputs['From Max'].default_value = x1
    L.link(nt, sep.outputs['X'], u.inputs['Value'])
    v = nt.nodes.new('ShaderNodeMapRange'); v.clamp = True
    v.inputs['From Min'].default_value = z0; v.inputs['From Max'].default_value = z1
    L.link(nt, sep.outputs['Z'], v.inputs['Value'])
    cm = nt.nodes.new('ShaderNodeCombineXYZ')
    L.link(nt, u.outputs['Result'], cm.inputs['X']); L.link(nt, v.outputs['Result'], cm.inputs['Y'])
    ti = nt.nodes.new('ShaderNodeTexImage'); ti.image = img; ti.extension = 'EXTEND'; ti.interpolation = 'Linear'
    L.link(nt, cm.outputs['Vector'], ti.inputs['Vector'])
    return ti.outputs['Color']


# ---------------------------------------------------------------- history maps (numpy)

def streak(arr, ppm, x0, z0, zbase, width, length, color_mul, strength, rng, wander=0.01, up=False):
    """A streak running DOWN from (x0, z0) (rust weeping from a fixing, rain from the coping).
    arr covers x from -xspan/2.., rows from zbase upwards at ppm px per metre."""
    h, w_all = arr.shape[:2]
    reach = width * 3.5 * 2.2 + 0.06
    c0 = max(0, int((x0 - reach - XMIN_H) * ppm)); c1 = min(w_all, int((x0 + reach - XMIN_H) * ppm) + 1)
    if c1 <= c0:
        return
    full = arr
    arr = full[:, c0:c1]
    xs = (np.arange(c0, c1) + 0.5) / ppm + XMIN_H
    zs = (np.arange(h) + 0.5) / ppm + zbase
    zz = zs[:, None]
    d = (z0 - zz) if not up else (zz - z0)
    along = np.clip(d / length, 0, None)
    fall = np.where(d >= 0, np.exp(-3.0 * along) * (1 - np.clip(along - 0.85, 0, 1) * 6).clip(0, 1), 0.0)
    # the streak wanders a little and widens as it runs
    wob = np.interp(zs, np.linspace(zs[0], zs[-1], 24), rng.normal(0, wander, 24))[:, None]
    wd = width * (1 + 1.2 * along)
    across = np.exp(-(((xs[None, :] - x0 - wob) / wd) ** 2))
    # broken: runs in drips, not a sprayed band
    brk = np.interp(zs, np.linspace(zs[0], zs[-1], 160), rng.uniform(0.55, 1.0, 160))[:, None]
    k = (strength * fall * across * brk)[..., None]
    full[:, c0:c1] = arr * ((1 - k) + k * np.array(color_mul, np.float32))


XMIN_H = -9.0


def wall_history(fixings, seed=11, ppm=110):
    """Rain streaks under the coping, rust from every steel fixing, biofilm at the floor."""
    global XMIN_H
    XMIN_H = -9.0
    w, h = int(18 * ppm), int(6.2 * ppm)
    zbase = -0.5
    rng = np.random.default_rng(seed)
    arr = np.ones((h, w, 3), np.float32)
    zs = (np.arange(h) + 0.5) / ppm + zbase
    xs = (np.arange(w) + 0.5) / ppm + XMIN_H
    # 1. rain: dark streaks from the coping drip line. Denser in places (where the coping joints leak).
    leaks = rng.uniform(-9, 9, 9)
    for _ in range(170):
        x0 = rng.choice(leaks) + rng.normal(0, 0.8) if rng.random() < 0.6 else rng.uniform(-9, 9)
        streak(arr, ppm, x0, WALL_H + 0.02, zbase, rng.uniform(0.015, 0.11), rng.uniform(0.8, 3.9),
               (0.50, 0.50, 0.48), rng.uniform(0.15, 0.55), rng, wander=0.012)
    # general weathering darker near the top (the coping sheds water down the face)
    top = np.clip((zs - (WALL_H - 3.4)) / 3.0, 0, 1) ** 1.3
    arr *= (1 - 0.28 * top)[:, None, None]
    # 2. rust weeping from steel fixed to the wall
    for (fx, fz, s) in fixings:
        for _ in range(rng.integers(1, 3)):
            streak(arr, ppm, fx + rng.normal(0, 0.01), fz, zbase, rng.uniform(0.008, 0.02),
                   rng.uniform(0.25, 0.9), (0.66, 0.44, 0.30), s * rng.uniform(0.5, 1.0), rng, wander=0.006)
    # 3. biofilm in the permanently wet band at the floor: dark olive, ragged top
    edge = 0.22 + 0.10 * np.interp(xs, np.linspace(-9, 9, 60), rng.uniform(-1, 1, 60))
    bio = np.clip((edge[None, :] - zs[:, None]) / 0.12, 0, 1)
    k = (0.55 * bio)[..., None]
    arr *= (1 - k) + k * np.array((0.50, 0.56, 0.40), np.float32)
    return np_image('WallHistory', arr.astype(np.float32)), (XMIN_H, XMIN_H + 18, zbase, zbase + 6.2)


def panel_history(pw, ph, letter_feet, brackets, seed=5, ppm=200):
    """On the panel (object space, x from -pw/2, z from 0): faint rust weeping from some letters' hidden
    studs, stronger under the steel brackets, and a dirtier foot."""
    global XMIN_H
    XMIN_H = -pw / 2
    w, h = int(pw * ppm), int(ph * ppm)
    rng = np.random.default_rng(seed)
    arr = np.ones((h, w, 3), np.float32)
    for (fx, fz, wid) in letter_feet:
        # two 6 mm steel studs per letter (one in a narrow one), behind the plate; rust runs down from each
        # stud's fixing and shows below the letter's foot (review round 1: the studs need visible weeps)
        studs = (fx - wid * 0.28, fx + wid * 0.28) if wid > 0.10 else (fx,)
        for sx in studs:
            if rng.random() < 0.62:
                streak(arr, ppm, sx + rng.normal(0, 0.006), fz + 0.01, 0.0, rng.uniform(0.004, 0.009),
                       rng.uniform(0.10, 0.42), (0.62, 0.42, 0.28), rng.uniform(0.35, 0.75), rng, wander=0.003)
    for (fx, fz) in brackets:
        for _ in range(2):
            streak(arr, ppm, fx + rng.normal(0, 0.015), fz, 0.0, rng.uniform(0.01, 0.02),
                   rng.uniform(0.4, 1.1), (0.62, 0.42, 0.28), rng.uniform(0.6, 0.9), rng, wander=0.006)
    zs = (np.arange(h) + 0.5) / ppm
    foot = np.clip(1 - zs / 0.25, 0, 1) ** 1.5
    arr *= (1 - 0.25 * foot)[:, None, None]
    return np_image('PanelHistory', arr.astype(np.float32)), (-pw / 2, pw / 2, 0.0, ph)


