def clear_water(name, density, scatter, ripple, ripple_scale, rough_front, rough_back, film, caustic, w_phase,
                shadow_k=1.0):
    """Clear water (round 2). lib_lookdev.water_mat with two fixes the technical review asked for:
      - the 'upward face' mask uses |true normal z|: Cycles flips the normal toward the ray on a back-facing hit,
        so shadow rays from under the water read 0 and the caustics never rendered (measured: 1 code value);
      - roughness 0.02 seen from above (crisp facets) and 0.10 seen from below (the underside's total internal
        reflection breaks up instead of mirroring the sentence: the phone's ghost of EVERY HIRE);
    and absorption per metre (TUNE absr/absg/absb), a little blue in-scatter for depth, and the sun's path through
    the volume shortened by shadow_k on shadow rays (they travel the unrefracted, ~2x longer path: tech minor)."""
    m = bpy.data.materials.new(name); m.use_nodes = True
    nt = m.node_tree; bsdf = nt.nodes['Principled BSDF']
    bsdf.inputs['Base Color'].default_value = (1, 1, 1, 1)
    bsdf.inputs['Transmission Weight'].default_value = 1.0
    bsdf.inputs['IOR'].default_value = 1.333
    tcf = nt.nodes.new('ShaderNodeTexCoord')
    fn = nt.nodes.new('ShaderNodeTexNoise'); fn.inputs['Scale'].default_value = 1.5; fn.inputs['Detail'].default_value = 8.0
    L.link(nt, tcf.outputs['Object'], fn.inputs['Vector'])
    fr = nt.nodes.new('ShaderNodeMapRange'); fr.interpolation_type = 'SMOOTHSTEP'
    fr.inputs['From Min'].default_value = 0.55; fr.inputs['From Max'].default_value = 0.70
    fr.inputs['To Min'].default_value = rough_front; fr.inputs['To Max'].default_value = max(rough_front, film)
    L.link(nt, fn.outputs['Fac'], fr.inputs['Value'])
    geo = nt.nodes.new('ShaderNodeNewGeometry')
    rm, f_, a_, b_, r_ = L.mix(nt, 'FLOAT')
    L.link(nt, geo.outputs['Backfacing'], f_); L.link(nt, fr.outputs['Result'], a_); b_.default_value = rough_back
    L.link(nt, r_, bsdf.inputs['Roughness'])
    tc = nt.nodes.new('ShaderNodeTexCoord')
    n1 = nt.nodes.new('ShaderNodeTexNoise'); n1.noise_dimensions = '4D'
    n1.inputs['Scale'].default_value = ripple_scale; n1.inputs['Detail'].default_value = 3.0
    n1.inputs['Roughness'].default_value = 0.45; n1.inputs['W'].default_value = w_phase
    L.link(nt, tc.outputs['Object'], n1.inputs['Vector'])
    n2 = nt.nodes.new('ShaderNodeTexWave'); n2.wave_type = 'BANDS'; n2.bands_direction = 'DIAGONAL'
    n2.inputs['Scale'].default_value = ripple_scale * 2.2; n2.inputs['Distortion'].default_value = 6.0
    n2.inputs['Detail'].default_value = 2.0; n2.inputs['Phase Offset'].default_value = w_phase * 6.0
    L.link(nt, tc.outputs['Object'], n2.inputs['Vector'])
    hgt = _m(nt, 'ADD', n1.outputs['Fac'], _m(nt, 'MULTIPLY', n2.outputs['Fac'], 0.1))
    sep = nt.nodes.new('ShaderNodeSeparateXYZ'); L.link(nt, geo.outputs['True Normal'], sep.inputs['Vector'])
    up = nt.nodes.new('ShaderNodeMapRange')
    up.inputs['From Min'].default_value = 0.6; up.inputs['From Max'].default_value = 0.95
    L.link(nt, _m(nt, 'ABSOLUTE', sep.outputs['Z']), up.inputs['Value'])            # the fix
    b = nt.nodes.new('ShaderNodeBump'); b.inputs['Distance'].default_value = 0.02
    L.link(nt, _m(nt, 'MULTIPLY', up.outputs['Result'], ripple), b.inputs['Strength'])
    L.link(nt, hgt, b.inputs['Height'])
    L.link(nt, b.outputs['Normal'], bsdf.inputs['Normal'])
    out = nt.nodes['Material Output']
    lp = nt.nodes.new('ShaderNodeLightPath')
    dens_k = _m(nt, 'MULTIPLY_ADD', lp.outputs['Is Shadow Ray'], shadow_k - 1.0, 1.0)
    va = nt.nodes.new('ShaderNodeVolumeAbsorption')
    a = (TUNE['absr'], TUNE['absg'], TUNE['absb'])
    mx = max(a)
    # Volume Absorption: coefficient = density * (1 - colour). Colour = 1 - a/mx at density mx gives a per metre.
    va.inputs['Color'].default_value = (*(1 - c / mx for c in a), 1)
    L.link(nt, _m(nt, 'MULTIPLY', dens_k, mx * density), va.inputs['Density'])
    vol = va.outputs['Volume']
    if scatter > 0:
        vs = nt.nodes.new('ShaderNodeVolumeScatter')
        vs.inputs['Color'].default_value = (0.78, 0.92, 1.0, 1)
        L.link(nt, _m(nt, 'MULTIPLY', dens_k, scatter), vs.inputs['Density'])
        vs.inputs['Anisotropy'].default_value = 0.65
        av = nt.nodes.new('ShaderNodeAddShader')
        L.link(nt, va.outputs['Volume'], av.inputs[0]); L.link(nt, vs.outputs['Volume'], av.inputs[1])
        vol = av.outputs['Shader']
    L.link(nt, vol, out.inputs['Volume'])
