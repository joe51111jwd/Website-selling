# Finish: fog glow, lateral colour, off-axis vignette (the lens axis is above a falling front), grain
# --------------------------------------------------------------------------------------------
def vignette_plate(w, h, strength, axis_y_px):
    """Natural falloff (cos^4 of the field angle) measured from the LENS AXIS, which a shifted front moves
    off the frame centre; `strength` blends it (a centre filter at < 1)."""
    name = f'vig_{w}x{h}_{strength:.2f}_{axis_y_px:.0f}'
    if name in bpy.data.images:
        return bpy.data.images[name]
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    mm_per_px = SENSOR / max(w, h)
    rx = (x + 0.5 - w / 2) * mm_per_px
    ry = (y + 0.5 - axis_y_px) * mm_per_px          # row 0 = bottom in Blender images
    th = np.arctan(np.sqrt(rx * rx + ry * ry) / focal)
    v = np.cos(th) ** 4
    v = 1.0 - strength * (1.0 - v)
    img = bpy.data.images.new(name, w, h, float_buffer=True, is_data=True)
    px = np.ones((h, w, 4), np.float32)
    px[..., 0] = px[..., 1] = px[..., 2] = v
    img.pixels.foreach_set(px.ravel()); img.pack()
    return img


def finish(seed=1):
    sc.use_nodes = True
    nt = sc.node_tree
    nt.nodes.clear()
    rl = nt.nodes.new('CompositorNodeRLayers')
    comp = nt.nodes.new('CompositorNodeComposite')
    cur = rl.outputs['Image']
    if TUNE['glare'] > 0:
        gl = nt.nodes.new('CompositorNodeGlare')
        L._set(gl, 'glare_type', 'Type', 'FOG_GLOW'); L._set(gl, 'quality', 'Quality', 'MEDIUM')
        L._set(gl, 'threshold', 'Threshold', 1.2); L._set(gl, 'size', 'Size', 8)
        L._set(gl, 'mix', 'Mix', -1.0 + TUNE['glare'])
        if 'Strength' in gl.inputs:
            gl.inputs['Strength'].default_value = TUNE['glare']
        L.link(nt, cur, gl.inputs['Image']); cur = gl.outputs['Image']
    if TUNE['dispersion'] > 0:
        ld = nt.nodes.new('CompositorNodeLensdist')
        L._set(ld, 'use_fit', 'Fit', True)
        if 'Dispersion' in ld.inputs:
            ld.inputs['Dispersion'].default_value = TUNE['dispersion']
        if 'Distortion' in ld.inputs:
            ld.inputs['Distortion'].default_value = 0.0
        L.link(nt, cur, ld.inputs['Image']); cur = ld.outputs['Image']
        scl = nt.nodes.new('CompositorNodeScale'); scl.space = 'RELATIVE'
        scl.inputs['X'].default_value = scl.inputs['Y'].default_value = 1.012
        L.link(nt, cur, scl.inputs['Image']); cur = scl.outputs['Image']
    w, h = A['w'], A['h']
    if TUNE['vignette'] > 0:
        axis_y = h / 2 - shift_y * max(w, h)        # shift_y < 0: the axis sits above the frame centre
        vi = nt.nodes.new('CompositorNodeImage'); vi.image = vignette_plate(w, h, TUNE['vignette'], axis_y)
        mm = nt.nodes.new('CompositorNodeMixRGB'); mm.blend_type = 'MULTIPLY'; mm.inputs['Fac'].default_value = 1.0
        L.link(nt, cur, mm.inputs[1]); L.link(nt, vi.outputs['Image'], mm.inputs[2]); cur = mm.outputs['Image']
    if TUNE['grain'] > 0:
        gi = nt.nodes.new('CompositorNodeImage'); gi.image = L._grain_plate(w, h, seed)
        tr = nt.nodes.new('CompositorNodeTranslate'); L._set(tr, 'wrap_axis', 'Wrap', 'BOTH')
        rnd = random.Random(sc.frame_current * 7919 + seed)
        tr.inputs['X'].default_value = rnd.randint(0, w); tr.inputs['Y'].default_value = rnd.randint(0, h)
        L.link(nt, gi.outputs['Image'], tr.inputs['Image'])
        mo = nt.nodes.new('CompositorNodeMixRGB'); mo.blend_type = 'OVERLAY'; mo.inputs['Fac'].default_value = TUNE['grain']
        L.link(nt, cur, mo.inputs[1]); L.link(nt, tr.outputs['Image'], mo.inputs[2]); cur = mo.outputs['Image']
    L.link(nt, cur, comp.inputs['Image'])


if not A['nopost']:
    finish()


