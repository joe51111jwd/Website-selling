def box_local(name, sx, sy, sz, loc, mat=None, bevel=0.0, segments=3):
    """A box sized (sx, sy, sz) whose mesh is centred on its object origin (so object-space textures
    travel with it when it moves)."""
    me = bpy.data.meshes.new(name)
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    for v in bm.verts:
        v.co = Vector((v.co.x * sx, v.co.y * sy, v.co.z * sz))
    if bevel > 0:
        bmesh.ops.bevel(bm, geom=bm.edges[:], offset=bevel, segments=segments, affect='EDGES', profile=0.5)
    bm.to_mesh(me); bm.free()
    if bevel > 0:
        L._sharp_by_angle(me, 50 if segments > 1 else 30)   # a flat chamfer keeps its arrises sharp
    ob = L.obj_from_mesh(name, me, mat)
    ob.location = loc
    return ob


def text_mesh(text, size, depth, bevel, res_u=12, name='line'):
    """Plimsoll Heavy, kerned, tracked 1.03, as a mesh standing up in XZ: front face at y = 0, body back to
    y = +depth, baseline z = 0, centred on x = 0."""
    font = bpy.data.fonts.load(FONT, check_existing=True)
    cu = bpy.data.curves.new(name, type='FONT')
    cu.body = text
    cu.font = font
    cu.size = size
    cu.align_x = 'CENTER'
    cu.space_character = 1.03
    blender_kern.apply(cu, FONT)
    cu.extrude = max(depth / 2 - bevel, 0.0001) if depth > 0 else 0.0
    cu.bevel_depth = bevel
    cu.bevel_resolution = 2
    cu.resolution_u = res_u
    tmp = bpy.data.objects.new(name + '_tmp', cu)
    sc.collection.objects.link(tmp)
    dg = bpy.context.evaluated_depsgraph_get()
    me = bpy.data.meshes.new_from_object(tmp.evaluated_get(dg))
    bpy.data.objects.remove(tmp)
    bpy.data.curves.remove(cu)
    for v in me.vertices:
        x, y, z = v.co
        v.co = Vector((x, -z + depth / 2, y))
    me.update()
