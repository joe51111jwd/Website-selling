def per_object_tone(m, lo=0.86, hi=1.06):
    """Each object (block) a slightly different tone, as no two precast pours match."""
    def sock(nt):
        oi = nt.nodes.new('ShaderNodeObjectInfo')
        mr = nt.nodes.new('ShaderNodeMapRange')
        mr.inputs['To Min'].default_value = lo; mr.inputs['To Max'].default_value = hi
        L.link(nt, oi.outputs['Random'], mr.inputs['Value'])
        cm = nt.nodes.new('ShaderNodeCombineXYZ')
        for c in ('X', 'Y', 'Z'):
            L.link(nt, mr.outputs['Result'], cm.inputs[c])
        return cm.outputs['Vector']
    return insert_multiply(m, sock)


